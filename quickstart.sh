#!/bin/sh
# Karna quickstart: starts compose.yaml (Kong with Karna, the Karna Console and a
# demo service), waits until it is ready, then prints where to go next.
#
#   ./quickstart.sh
#
# Same as `docker compose up -d --build`, plus the instructions. Safe to run
# again, and the way to update after a `git pull`.
set -e
cd "$(dirname "$0")"

if ! docker compose version >/dev/null 2>&1; then
  echo "Docker with the Compose plugin is required: https://docs.docker.com/get-docker/" >&2
  exit 1
fi

CONSOLE_PORT="${KARNA_CONSOLE_PORT:-9080}"
PROXY_PORT="${KARNA_PROXY_PORT:-8000}"

# A random Postgres password, written to .env once, for a fresh install only:
# a database volume that already exists keeps the password it was created with.
if ! grep -q '^KARNA_PG_PASSWORD=' .env 2>/dev/null && [ -z "${KARNA_PG_PASSWORD:-}" ]; then
  project="$(docker compose -f compose.yaml config 2>/dev/null | sed -n 's/^name: //p' | head -n 1)"
  if [ -z "$(docker volume ls -q --filter "label=com.docker.compose.project=${project:-karna}" \
                                   --filter "label=com.docker.compose.volume=pg_data")" ]; then
    pw="$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 32)"
    printf '\n# Postgres password for compose.yaml, generated by quickstart.sh.\nKARNA_PG_PASSWORD=%s\n' "$pw" >> .env
    chmod 600 .env
  fi
fi

echo "Starting Karna. The first run builds the images and takes a few minutes."
# --build: after a `git pull` the images are rebuilt from the new sources;
# unchanged layers come from the cache, so a rerun takes seconds.
docker compose -f compose.yaml up -d --build --wait

# The one-time setup token while no admin exists, empty once it does.
token="$(docker compose -f compose.yaml exec -T dashboard-api python -c '
import auth
token, from_env = auth.ensure_setup_token()
print("" if token is None else ("(the value of KARNA_DASH_SETUP_TOKEN)" if from_env else token))
' 2>/dev/null)" || token=""

cat <<MSG

Karna is up.

  Console   http://127.0.0.1:${CONSOLE_PORT}
  Proxy     http://127.0.0.1:${PROXY_PORT}   (demo service, Karna in blocking mode)

MSG

if [ -n "$token" ]; then
  cat <<MSG
Create the admin account: open the console and enter this one-time setup token

  ${token}

It stops working once the admin exists.

MSG
else
  echo "Sign in to the console with your admin account."
  echo
fi

cat <<MSG
Send the demo service an attack and watch it in the console (Events):

  curl "http://127.0.0.1:${PROXY_PORT}/?q=<script>alert(1)</script>"

Logs:    docker compose logs -f
Stop:    docker compose down        (add -v to also delete all data)
Docs:    dashboard/README.md
MSG
